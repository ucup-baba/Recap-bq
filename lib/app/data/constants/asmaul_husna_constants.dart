/// 99 Asmaul Husna - The Beautiful Names of Allah
class AsmaulHusna {
  final int number;
  final String arabic;
  final String latin;
  final String meaning;
  final String description;

  const AsmaulHusna({
    required this.number,
    required this.arabic,
    required this.latin,
    required this.meaning,
    required this.description,
  });
}

/// Get Asmaul Husna for today based on day of year
AsmaulHusna getTodayAsmaulHusna() {
  final now = DateTime.now();
  final dayOfYear = now.difference(DateTime(now.year, 1, 1)).inDays;
  final index = dayOfYear % 99; // 0-98
  return asmaulHusnaList[index];
}

